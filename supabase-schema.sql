-- 1. Document Sync Table (Atomic Full-State Synchronization)
CREATE TABLE IF NOT EXISTS public.finance_sync (
  id TEXT PRIMARY KEY DEFAULT 'current',
  data JSONB NOT NULL,
  version INT NOT NULL DEFAULT 3,
  mode TEXT NOT NULL DEFAULT 'custom',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.finance_sync ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read on finance_sync" 
  ON public.finance_sync FOR SELECT 
  TO anon, authenticated 
  USING (true);

CREATE POLICY "Allow public insert on finance_sync" 
  ON public.finance_sync FOR INSERT 
  TO anon, authenticated 
  WITH CHECK (true);

CREATE POLICY "Allow public update on finance_sync" 
  ON public.finance_sync FOR UPDATE 
  TO anon, authenticated 
  USING (true) 
  WITH CHECK (true);

CREATE POLICY "Allow public delete on finance_sync" 
  ON public.finance_sync FOR DELETE 
  TO anon, authenticated 
  USING (true);


-- 2. Relational Tables (Accounts, Categories, Transactions, Targets)

-- Accounts Table
CREATE TABLE IF NOT EXISTS public.accounts (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('cash', 'bank', 'savings', 'investment', 'liability')),
  initial_balance_grosze BIGINT NOT NULL DEFAULT 0,
  color TEXT NOT NULL DEFAULT '#ffffff',
  include_in_liquid BOOLEAN NOT NULL DEFAULT true,
  note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.accounts ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public all on accounts" ON public.accounts FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- Categories Table
CREATE TABLE IF NOT EXISTS public.categories (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('expense', 'income')),
  icon TEXT NOT NULL DEFAULT 'shopping-bag',
  color TEXT NOT NULL DEFAULT '#ffffff',
  monthly_budget_grosze BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public all on categories" ON public.categories FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- Transactions Table
CREATE TABLE IF NOT EXISTS public.transactions (
  id TEXT PRIMARY KEY,
  type TEXT NOT NULL CHECK (type IN ('expense', 'income', 'transfer')),
  amount_grosze BIGINT NOT NULL,
  date TEXT NOT NULL,
  time TEXT,
  account_id TEXT NOT NULL REFERENCES public.accounts(id) ON DELETE CASCADE,
  to_account_id TEXT REFERENCES public.accounts(id) ON DELETE SET NULL,
  category_id TEXT NOT NULL,
  title TEXT NOT NULL,
  note TEXT,
  is_planned BOOLEAN DEFAULT false,
  is_adjustment BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public all on transactions" ON public.transactions FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- Targets Table
CREATE TABLE IF NOT EXISTS public.targets (
  id TEXT PRIMARY KEY DEFAULT 'current',
  monthly_expense_limit_grosze BIGINT NOT NULL DEFAULT 680000,
  monthly_income_goal_grosze BIGINT NOT NULL DEFAULT 1250000,
  yearly_overrides JSONB,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.targets ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public all on targets" ON public.targets FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- 3. Todos Table (for testing / compatibility with user prompt example)
