'use client';

import React, { useRef, useState } from 'react';
import {
  Check,
  Cloud,
  Copy,
  Database,
  Download,
  RefreshCw,
  Sparkles,
  Trash2,
  Upload,
} from 'lucide-react';
import { FinanceDB } from '@/lib/types';
import { useFinance } from '../FinanceProvider';
import { ModalDrawer } from '../ui/ModalDrawer';
import { useToast } from '../ui/ToastProvider';

const SUPABASE_SCHEMA_SQL = `-- 1. Document Sync Table (Atomic State Synchronization)
CREATE TABLE IF NOT EXISTS public.finance_sync (
  id TEXT PRIMARY KEY DEFAULT 'current',
  data JSONB NOT NULL,
  version INT NOT NULL DEFAULT 3,
  mode TEXT NOT NULL DEFAULT 'custom',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.finance_sync ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public all on finance_sync" 
  ON public.finance_sync FOR ALL TO anon, authenticated 
  USING (true) WITH CHECK (true);

-- 2. Todos Table (verification table from guide)
CREATE TABLE IF NOT EXISTS public.todos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);
ALTER TABLE public.todos ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public all on todos" ON public.todos FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- 3. User Accounts & WebAuthn Passkeys (Face ID / Biometrics)
CREATE TABLE IF NOT EXISTS public.app_users (
  login TEXT PRIMARY KEY,
  display_name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);
ALTER TABLE public.app_users ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public all on app_users" ON public.app_users FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

CREATE TABLE IF NOT EXISTS public.passkey_credentials (
  id TEXT PRIMARY KEY,
  username TEXT NOT NULL,
  public_key_b64 TEXT NOT NULL,
  counter BIGINT NOT NULL DEFAULT 0,
  transports JSONB,
  device_label TEXT NOT NULL DEFAULT 'Urządzenie biometryczne',
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);
ALTER TABLE public.passkey_credentials ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public all on passkey_credentials" ON public.passkey_credentials FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
`;

export function CookieDbModal({
  open,
  onClose,
}: {
  open: boolean;
  onClose: () => void;
}): React.ReactElement {
  const {
    db,
    storageStats,
    supabaseConfig,
    syncWithSupabase,
    exportToSupabase,
    resetToClean,
    restoreDemo,
    importDatabase,
  } = useFinance();
  const { pushToast } = useToast();
  const fileInputRef = useRef<HTMLInputElement>(null);
  const [confirmClear, setConfirmClear] = useState(false);
  const [copiedSql, setCopiedSql] = useState(false);
  const [syncing, setSyncing] = useState(false);

  const handleCopySql = () => {
    navigator.clipboard.writeText(SUPABASE_SCHEMA_SQL);
    setCopiedSql(true);
    pushToast({
      message: 'Skopiowano kod migracji SQL do schowka',
      detail: 'Wklej go w Supabase Dashboard -> SQL Editor i kliknij Run.',
      tone: 'info',
    });
    setTimeout(() => setCopiedSql(false), 3000);
  };

  const handleManualSync = async () => {
    setSyncing(true);
    try {
      const ok = await exportToSupabase();
      if (ok) {
        pushToast({
          message: 'Zsynchronizowano z chmurą Supabase',
          tone: 'info',
        });
      } else {
        pushToast({
          message: 'Baza Supabase wymaga utworzenia tabel SQL',
          detail: 'Skopiuj kod migracji poniżej i uruchom w Supabase SQL Editor.',
          tone: 'coral',
        });
      }
    } finally {
      setSyncing(false);
    }
  };

  const handleManualPull = async () => {
    setSyncing(true);
    try {
      const ok = await syncWithSupabase();
      if (ok) {
        pushToast({
          message: 'Pobrano dane z chmury Supabase',
          tone: 'info',
        });
      } else {
        pushToast({
          message: 'Brak danych w Supabase lub tabele nie istnieją',
          tone: 'coral',
        });
      }
    } finally {
      setSyncing(false);
    }
  };

  const handleExport = () => {
    const blob = new Blob([JSON.stringify(db, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `cashflow-backup-${db.updatedAt}.json`;
    a.click();
    URL.revokeObjectURL(url);
    pushToast({
      message: 'Wyeksportowano kopię bazy JSON',
      tone: 'info',
    });
  };

  const handleImport = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    try {
      const text = await file.text();
      const parsed = JSON.parse(text) as FinanceDB;
      if (!parsed || !Array.isArray(parsed.accounts) || !Array.isArray(parsed.transactions)) {
        throw new Error('Nieprawidłowy format');
      }
      importDatabase(parsed);
      pushToast({
        message: 'Zaimportowano dane do pamięci',
        detail: `${parsed.transactions.length} operacji · ${parsed.accounts.length} kont`,
        tone: 'info',
      });
      onClose();
    } catch {
      pushToast({
        message: 'Błąd importu pliku JSON',
        detail: 'Sprawdź czy plik pochodzi z eksportu CashFlow.',
        tone: 'coral',
      });
    } finally {
      e.target.value = '';
    }
  };

  return (
    <ModalDrawer
      open={open}
      onClose={() => {
        setConfirmClear(false);
        onClose();
      }}
      title="Baza danych & Chmura"
      subtitle="Zarządzaj lokalnymi danymi sesji oraz synchronizacją w czasie rzeczywistym z Supabase."
    >
      <div className="space-y-4">
        {/* Supabase Cloud Connection Panel */}
        <div className="rounded-2xl ios-glass-inset p-4 space-y-3">
          <div className="flex items-center justify-between">
            <span className="inline-flex items-center gap-2 text-xs font-bold text-white">
              <Cloud className="w-4 h-4 text-white" />
              Chmura Supabase
            </span>
            <div className="flex items-center gap-1.5">
              <span
                className={`w-2 h-2 rounded-full ${
                  supabaseConfig.tablesReady
                    ? 'bg-emerald-400 animate-pulse'
                    : 'bg-amber-400'
                }`}
              />
              <span className="text-[11px] font-bold text-neutral-300">
                {supabaseConfig.tablesReady
                  ? 'Połączono (Postgres)'
                  : 'Wymaga migracji SQL'}
              </span>
            </div>
          </div>

          <div className="text-xs text-neutral-300 font-mono bg-white/[0.04] border border-white/[0.08] p-2.5 rounded-xl break-all">
            {(() => {
              try {
                const raw = process.env.NEXT_PUBLIC_SUPABASE_URL;
                return raw ? new URL(raw).host : 'Supabase Cloud';
              } catch {
                return 'Supabase Cloud';
              }
            })()}
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 pt-1">
            <button
              type="button"
              onClick={handleCopySql}
              className="w-full flex items-center justify-center gap-2 rounded-xl bg-white/95 hover:bg-white active:scale-[0.98] text-black px-3.5 py-2 text-xs font-bold transition-all cursor-pointer sm:col-span-2 shadow-[0_4px_14px_rgba(255,255,255,0.2)]"
            >
              {copiedSql ? (
                <>
                  <Check className="w-3.5 h-3.5" /> Skopiowano SQL!
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" /> Kopiuj kod migracji SQL
                </>
              )}
            </button>

            <button
              type="button"
              onClick={handleManualSync}
              disabled={syncing}
              className="w-full flex items-center justify-center gap-2 rounded-xl ios-glass-pill active:scale-[0.98] text-white px-3.5 py-2 text-xs font-bold transition-all cursor-pointer"
            >
              <RefreshCw className={`w-3.5 h-3.5 ${syncing ? 'animate-spin' : ''}`} />
              Wyślij do chmury
            </button>

            <button
              type="button"
              onClick={handleManualPull}
              disabled={syncing}
              className="w-full flex items-center justify-center gap-2 rounded-xl ios-glass-pill active:scale-[0.98] text-white px-3.5 py-2 text-xs font-bold transition-all cursor-pointer"
            >
              <Download className="w-3.5 h-3.5" />
              Pobierz z chmury
            </button>
          </div>
        </div>

        {/* Local Storage Stats */}
        <div className="rounded-2xl ios-glass-inset p-4 space-y-3">
          <div className="flex items-center justify-between">
            <span className="inline-flex items-center gap-2 text-xs font-bold text-white">
              <Database className="w-4 h-4 text-white" />
              Lokalna pamięć podręczna (Cookies)
            </span>
            <span className="text-[11px] font-bold px-2.5 py-0.5 rounded-full bg-white/10 text-white border border-white/20">
              {db.mode === 'demo' ? 'Dane testowe' : 'Własne dane'}
            </span>
          </div>

          <div className="grid grid-cols-3 gap-2 text-center">
            <div className="rounded-xl bg-white/[0.04] border border-white/[0.08] p-3">
              <div className="text-[11px] text-neutral-400">Operacje</div>
              <div className="text-base font-extrabold tabular-nums text-white">
                {db.transactions.length}
              </div>
            </div>
            <div className="rounded-xl bg-white/[0.04] border border-white/[0.08] p-3">
              <div className="text-[11px] text-neutral-400">Cookies</div>
              <div className="text-base font-extrabold tabular-nums text-white">
                {storageStats.chunkCount + 1} szt.
              </div>
            </div>
            <div className="rounded-xl bg-white/[0.04] border border-white/[0.08] p-3">
              <div className="text-[11px] text-neutral-400">Rozmiar LZ</div>
              <div className="text-base font-extrabold tabular-nums text-white">
                {(storageStats.encodedBytes / 1024).toFixed(1)} KB
              </div>
            </div>
          </div>

          <div className="space-y-1.5 pt-1">
            <div className="flex items-center justify-between text-[11px] text-neutral-400">
              <span>Zużycie bezpiecznego limitu (12 KB)</span>
              <span className="tabular-nums font-semibold text-white">{storageStats.usagePercent}%</span>
            </div>
            <div
              role="progressbar"
              aria-valuenow={storageStats.usagePercent}
              aria-valuemin={0}
              aria-valuemax={100}
              className="h-2 rounded-full bg-white/[0.08] overflow-hidden"
            >
              <div
                className={`h-full rounded-full transition-all duration-300 ${
                  storageStats.usagePercent >= 85
                    ? 'bg-amber-400'
                    : 'bg-[#2dd4bf]'
                }`}
                style={{ width: `${Math.max(4, Math.min(100, storageStats.usagePercent))}%` }}
              />
            </div>
          </div>
        </div>

        {/* JSON Export / Import */}
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
          <button
            type="button"
            onClick={handleExport}
            className="flex items-center justify-center gap-2 rounded-2xl ios-glass-pill active:scale-[0.98] px-4 py-3 text-xs sm:text-sm font-bold text-white transition-all cursor-pointer"
          >
            <Download className="w-4 h-4 text-white" />
            Eksportuj JSON
          </button>

          <button
            type="button"
            onClick={() => fileInputRef.current?.click()}
            className="flex items-center justify-center gap-2 rounded-2xl ios-glass-pill active:scale-[0.98] px-4 py-3 text-xs sm:text-sm font-bold text-white transition-all cursor-pointer"
          >
            <Upload className="w-4 h-4 text-white" />
            Importuj JSON
          </button>
          <input
            ref={fileInputRef}
            type="file"
            accept=".json,application/json"
            onChange={handleImport}
            className="hidden"
          />
        </div>

        {/* Demo Data & Reset */}
        <div className="border-t border-[#1a1e28] pt-4 space-y-2.5">
          <button
            type="button"
            onClick={() => {
              restoreDemo();
              setConfirmClear(false);
              pushToast({
                message: 'Załadowano dane demonstracyjne (2024–2026)',
                tone: 'info',
              });
              onClose();
            }}
            className="w-full flex items-center justify-center gap-2 rounded-2xl bg-[#12151e] hover:bg-[#1a202c] border border-[#222938] px-4 py-3 text-xs sm:text-sm font-bold text-white transition-colors cursor-pointer"
          >
            <Sparkles className="w-4 h-4 text-amber-300" />
            Przywróć dane demonstracyjne (2024–2026)
          </button>

          {!confirmClear ? (
            <button
              type="button"
              onClick={() => setConfirmClear(true)}
              className="w-full flex items-center justify-center gap-2 rounded-2xl bg-red-500/10 hover:bg-red-500/20 border border-red-500/25 px-4 py-3 text-xs sm:text-sm font-bold text-[#f87171] transition-colors cursor-pointer"
            >
              <Trash2 className="w-4 h-4" />
              Wyczyść bazę i zacznij od 0 zł
            </button>
          ) : (
            <div className="rounded-2xl bg-red-500/12 border border-red-500/35 p-4 flex flex-col sm:flex-row sm:items-center justify-between gap-3 animate-fade-in">
              <span className="text-xs font-semibold text-red-200">
                Usunąć wszystkie transakcje i wyzerować konta?
              </span>
              <div className="flex items-center gap-2 shrink-0">
                <button
                  type="button"
                  onClick={() => setConfirmClear(false)}
                  className="px-3 py-1.5 rounded-full text-xs font-medium text-neutral-400 hover:text-white cursor-pointer"
                >
                  Anuluj
                </button>
                <button
                  type="button"
                  onClick={() => {
                    resetToClean();
                    setConfirmClear(false);
                    pushToast({
                      message: 'Baza wyczyszczona (0 zł)',
                      tone: 'info',
                    });
                    onClose();
                  }}
                  className="px-4 py-1.5 rounded-full bg-red-500 hover:bg-red-600 text-white text-xs font-black cursor-pointer shadow-sm"
                >
                  Tak, wyczyść
                </button>
              </div>
            </div>
          )}
        </div>
      </div>
    </ModalDrawer>
  );
}
